"""Generate alembic/sql/0002_data_tables.sql: the ETL-owned Postgres tables, from a pg_dump of
the sandbox schema (clevrr-backend-2.0/alembic/baseline/schema.sql, structure only).

    uv run python scripts/pg_tables.py <path to schema.sql>

For each table in ETL_TABLES it keeps: CREATE TABLE, its sequences (CREATE, OWNED BY, the
column default), PRIMARY KEY / UNIQUE / CHECK constraints and indexes. Foreign keys are dropped
(they point at app-owned tables). `public.` goes from table and sequence names, so the objects
land in the migration's target schema; it stays on function calls (extensions live in public).
Every statement is idempotent: on a fresh schema everything is created, on `public` at cut-over
nothing that exists is touched. Statements are separated by a `--;;` line.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "alembic" / "sql" / "0002_data_tables.sql"
SEPARATOR = "\n--;;\n"

ETL_TABLES = (
    # Shopify (sales, catalog)
    "raw_shopify_orders", "raw_shopify_order_lines", "raw_shopify_refunds",
    "raw_shopify_order_refund_lines", "raw_shopify_order_note_attributes",
    "raw_shopify_products", "raw_shopify_collects", "raw_shopify_collections",
    "orders", "order_lines", "refunds", "refund_lines", "order_click_attribution",
    "ad_product_mapping", "products", "product_variants", "product_cost_history",
    # Meta
    "raw_meta_ad_insights", "raw_meta_ad_creative", "raw_meta_campaigns", "raw_meta_ad_sets",
    "raw_meta_ads", "raw_meta_ad_insights_by_region", "raw_meta_account_insights",
    "advertising", "campaign_structure", "advertising_geo_daily",
    # Google Ads
    "raw_google_ads_ad_group_ad", "raw_google_ads_campaign", "raw_google_ads_ad_group",
    "raw_google_ads_conv_action_perf", "raw_google_ads_campaign_conv_action_perf",
    "raw_google_ads_conversion_action", "raw_google_ads_ad_creative",
    "raw_google_ads_shopping_perf", "raw_google_ads_asset_group_product_perf",
    "google_ads_product_performance",
    # Delhivery
    "raw_shipping_tracking", "shipments", "shipment_scans",
)  # fmt: skip

# A function call has no space before its parenthesis; a table name in CREATE TABLE has one.
_PUBLIC_NAME = re.compile(r"\bpublic\.(\w+)\b(?!\()")


def statements(dump: str) -> list[str]:
    lines = [ln for ln in dump.splitlines() if not ln.startswith(("--", "\\"))]
    return [s.strip() for s in "\n".join(lines).split(";\n") if s.strip()]


def _table_of(stmt: str) -> str | None:
    patterns = (
        r"^CREATE TABLE public\.(\w+) \(",
        r"^ALTER TABLE ONLY public\.(\w+)\s",
        r"^CREATE (?:UNIQUE )?INDEX \w+ ON public\.(\w+) ",
        r"^ALTER SEQUENCE public\.\w+ OWNED BY public\.(\w+)\.",
    )
    for pattern in patterns:
        match = re.match(pattern, stmt, re.DOTALL)
        if match:
            return match.group(1)
    return None


def _owned_sequences(stmts: list[str]) -> dict[str, str]:
    """sequence name -> table name, from ALTER SEQUENCE ... OWNED BY."""
    owned: dict[str, str] = {}
    for stmt in stmts:
        match = re.match(r"^ALTER SEQUENCE public\.(\w+) OWNED BY public\.(\w+)\.", stmt)
        if match:
            owned[match.group(1)] = match.group(2)
    return owned


def _idempotent(stmt: str) -> str | None:
    stmt = _PUBLIC_NAME.sub(r"\1", stmt)
    if stmt.startswith("CREATE TABLE "):
        return stmt.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
    if stmt.startswith("CREATE SEQUENCE "):
        return stmt.replace("CREATE SEQUENCE ", "CREATE SEQUENCE IF NOT EXISTS ", 1)
    if re.match(r"^CREATE (UNIQUE )?INDEX ", stmt):
        return re.sub(r"^CREATE (UNIQUE )?INDEX ", r"CREATE \1INDEX IF NOT EXISTS ", stmt, count=1)
    if "ADD CONSTRAINT" in stmt:
        if "FOREIGN KEY" in stmt:
            return None
        return (
            "DO $$ BEGIN\n" + stmt + ";\nEXCEPTION WHEN duplicate_object OR duplicate_table"
            " OR invalid_table_definition THEN NULL;\nEND $$"
        )
    return stmt  # ALTER SEQUENCE OWNED BY, ALTER COLUMN SET DEFAULT: repeatable


def generate(dump: str) -> str:
    stmts = statements(dump)
    owned = _owned_sequences(stmts)
    wanted = set(ETL_TABLES)
    picked: list[str] = []
    for stmt in stmts:
        seq = re.match(r"^CREATE SEQUENCE public\.(\w+)", stmt)
        table = owned.get(seq.group(1)) if seq else _table_of(stmt)
        if table in wanted:
            out = _idempotent(stmt)
            if out:
                picked.append(out)
    missing = wanted - {t for t in wanted if any(f"EXISTS {t} (" in s for s in picked)}
    if missing:
        raise SystemExit(f"Not in the dump: {sorted(missing)}")
    header = (
        "-- Generated by scripts/pg_tables.py from the sandbox pg_dump. Do not edit by hand.\n"
        f"-- {len(ETL_TABLES)} ETL-owned tables, {len(picked)} statements."
    )
    return header + SEPARATOR + SEPARATOR.join(picked) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    sql = generate(Path(sys.argv[1]).read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {sql.count('--;;')} statements")
    return 0


if __name__ == "__main__":
    sys.exit(main())

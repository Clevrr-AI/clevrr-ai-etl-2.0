"""Generate clickhouse_migrations/0001_baseline.sql from a dump of the sandbox ClickHouse schema
(clevrr-backend-2.0/clickhouse/baseline/schema.sql, structure only).

    uv run python scripts/ch_baseline.py <path to schema.sql>

The dump names the database (`clevrr_db.`), the cluster ('sbx-cluster') and hard-codes
`clevrr_db` in every replicated table's ZooKeeper path. The output uses `${db}` and `${cluster}`
(filled in by `etl ch-migrate` from the settings) and gives every replicated table the path
`/clickhouse/tables/{shard}/${db}/<table>`, so a second database (clevrr_db_v2) never shares a
path with legacy's tables. `{shard}` and `{replica}` stay: they are ClickHouse server macros.
Statements are separated by a `--;;` line.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "clickhouse_migrations" / "0001_baseline.sql"
SEPARATOR = "\n--;;\n"

_CREATE = re.compile(r"^CREATE TABLE clevrr_db\.(\w+)")
_PATH = re.compile(r"Replicated(\w*MergeTree)\('/clickhouse/tables/\{shard\}/[^']*'")
_DISTRIBUTED = re.compile(r"Distributed\('[^']*',\s*'clevrr_db',\s*'(\w+)'")


def statements(dump: str) -> list[str]:
    body = "\n".join(ln for ln in dump.splitlines() if not ln.startswith("--"))
    return [s.strip().rstrip(";") for s in body.split(";\n") if s.strip()]


def convert(stmt: str) -> str:
    match = _CREATE.match(stmt)
    if not match:
        raise SystemExit(f"Not a CREATE TABLE: {stmt[:80]}")
    table = match.group(1)
    stmt = _CREATE.sub(
        f"CREATE TABLE IF NOT EXISTS ${{db}}.{table} ON CLUSTER '${{cluster}}'", stmt
    )
    stmt = _PATH.sub(rf"Replicated\1('/clickhouse/tables/{{shard}}/${{db}}/{table}'", stmt)
    stmt = _DISTRIBUTED.sub(r"Distributed('${cluster}', '${db}', '\1'", stmt)
    if "clevrr_db" in stmt:
        raise SystemExit(f"{table}: a clevrr_db reference is left")
    return stmt


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    stmts = [convert(s) for s in statements(Path(sys.argv[1]).read_text(encoding="utf-8"))]
    header = (
        "-- Generated by scripts/ch_baseline.py from the sandbox ClickHouse schema"
        " (2026-10-09 dump)."
        f"\n-- {len(stmts)} tables. ${{db}} and ${{cluster}} come from the settings."
    )
    OUT.write_text(header + SEPARATOR + SEPARATOR.join(stmts) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(stmts)} statements")
    return 0


if __name__ == "__main__":
    sys.exit(main())
